#!/bin/bash
# Writes third_party/rust-crates.txt: the licence notice of every Rust
# crate linked into the App and the background service (the runtime
# dependency graph of core/, build-time-only crates such as proc macros
# left out). Re-run after changing core/Cargo.toml or Cargo.lock;
# local-checks asserts the file lists exactly the current crates.
#
#   scripts/make-rust-notices.sh [--check]
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/third_party/rust-crates.txt"

crates=$(cd "$ROOT/core" && cargo metadata --format-version 1 --locked --filter-platform aarch64-apple-darwin 2>/dev/null |
python3 -I -c '
import json, sys
m = json.load(sys.stdin)
nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
pkgs = {p["id"]: p for p in m["packages"]}
# Runtime graph: normal edges only, and never through a proc macro
# (its code runs in the compiler, nothing of it is linked).
seen, todo = set(), [m["resolve"]["root"]]
while todo:
    for d in nodes[todo.pop()]["deps"]:
        p = pkgs[d["pkg"]]
        if any(t == ["proc-macro"] for t in [k["kind"] for k in p["targets"]]):
            continue
        if any(k["kind"] is None for k in d["dep_kinds"]) and d["pkg"] not in seen:
            seen.add(d["pkg"]); todo.append(d["pkg"])
for i in sorted(seen, key=lambda i: pkgs[i]["name"]):
    p = pkgs[i]
    print("\t".join([p["name"], p["version"], p["license"] or "", p["repository"] or "",
                     __import__("os").path.dirname(p["manifest_path"])]))
')

render() {
    echo "Rust crates linked into AlwaysConnect (libalwaysconnect_core.a)"
    echo "Generated by scripts/make-rust-notices.sh from core/Cargo.lock."
    echo "Each crate is used under the MIT option of its licence; the"
    echo "Apache-2.0 text is in third_party/licenses/Apache-2.0.txt."
    echo
    while IFS=$'\t' read -r name version license repo dir; do
        echo "================================================================"
        echo "$name $version  ($license)  $repo"
        echo "================================================================"
        mit=""
        for f in LICENSE-MIT LICENSE-MIT.md LICENSE; do [ -f "$dir/$f" ] && { mit="$dir/$f"; break; }; done
        [ -n "$mit" ] || { echo "no MIT licence file for $name in $dir" >&2; exit 1; }
        cat "$mit"
        echo
    done <<< "$crates"
}

if [ "${1:-}" = "--check" ]; then
    diff <(render) "$OUT" >/dev/null || { echo "third_party/rust-crates.txt is out of date: run scripts/make-rust-notices.sh" >&2; exit 1; }
    echo "rust-crates.txt up to date"
else
    render > "$OUT"
    echo "wrote $OUT ($(grep -c '^====' "$OUT" | awk '{print $1/2}') crates)"
fi
